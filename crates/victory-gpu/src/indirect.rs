//! Indirect execution's arguments, bounded before the GPU reads them. The
//! title's own compute passes write most of them; a pass we drop or
//! translate wrongly leaves whatever the memory held, and a draw of four
//! billion vertices or a dispatch past the host's limits runs until the
//! host resets the display driver. So active records are copied and clamped
//! on the GPU into a device-local scratch buffer, just before execution, by a
//! compute shader of ours (HLSL compiled by the system's compiler; a 5.1
//! shader with its root signature inside), leaving the title's argument and
//! count buffers untouched.
//!
//! When a count buffer is given, threads at or past `min(max, count)` return
//! immediately without charging the list's budget or reading uninitialized
//! tail slots. Each list has a budget (2^27 vertex instances or threads,
//! groups counted as 64 threads, mesh groups as 128): active records past it
//! run empty, saturating without 32-bit wraparound so a list of thousands of
//! garbage records cannot run for seconds either.
//!
//! shortcut: the bounds (2^24 vertices, 2^26 vertex instances, 65,535
//! groups per dimension and 2^20 per dispatch, one-dimensional mesh
//! dispatches, the budget) cut legitimate work beyond them; raise them if
//! the title needs more.
//!
//! Experiment switches, read once when the clamp is compiled (each is a
//! define of the shader, so without them it compiles exactly as before):
//! `VICTORY_MESH_2D=1` keeps a mesh dispatch's y and z (each at most
//! 65,535 and the whole at most 2^22 groups, the host's limits) instead of
//! forcing them to 1; `VICTORY_INDIRECT_BUDGET_SHIFT=n` makes the budget
//! 2^n (n at most 31; 27 by default). With `diagnostics` and
//! `VICTORY_INDIRECT_STATS=1` the clamp also counts, per kind, what it saw
//! and did, in the list's budget buffer past its first word, logged per
//! frame about once a second ([`log_stats`]).

use windows::Win32::Graphics::Direct3D::Fxc::D3DCompile;
use windows::Win32::Graphics::Direct3D::{D3D_SHADER_MACRO, ID3DBlob};
use windows::Win32::Graphics::Direct3D12::*;
use windows::core::{PCSTR, s};

use crate::host::{HostList, host, transition};

const SOURCE: &str = r#"
#define RS "RootConstants(num32BitConstants=6, b0), SRV(t0), SRV(t1), UAV(u0), UAV(u1)"
cbuffer Record : register(b0) {
    uint kind;
    uint stride;
    uint records;
    uint args_offset;
    uint has_count;
    uint count_offset;
};
ByteAddressBuffer src_args : register(t0);
ByteAddressBuffer count_buf : register(t1);
RWByteAddressBuffer dst_args : register(u0);
// The list's work so far (vertex instances, threads): past the budget,
// records run empty.
RWByteAddressBuffer budget : register(u1);
#ifndef BUDGET_SHIFT
#define BUDGET_SHIFT 27
#endif
static const uint BUDGET = 1u << BUDGET_SHIFT;
#ifdef MESH_2D
// Groups of one mesh dispatch (the host's limit); y and z shrink first.
static const uint MESH_GROUPS = 1u << 22;
#endif
#ifdef STATS
// Counters per kind (draws, dispatches, mesh), 8 words each, in the
// budget buffer from here on: records, all-zero records, records over the
// budget, records clamped, mesh max y and z seen, launched (low, high).
static const uint STATS_AT = 64u;
#endif
// Groups of one dispatch; more run empty.
static const uint GROUPS = 1u << 20;
[RootSignature(RS)]
[numthreads(64, 1, 1)]
void main(uint3 id : SV_DispatchThreadID) {
    uint eff_count = records;
    if (has_count != 0) {
        eff_count = min(eff_count, count_buf.Load(count_offset));
    }
    if (id.x >= eff_count) return;
    uint src_at = args_offset + id.x * stride;
    uint dst_at = id.x * stride;
    uint cost;
    uint2 draw_counts = uint2(0, 0);
    uint3 groups = uint3(0, 0, 0);
#ifdef STATS
    // The counted words as the title wrote them (draws: the first two).
    uint3 seen = src_args.Load3(src_at);
#endif
    if (kind <= 1) {
        // Draws: vertex or index count, then instances.
        uint count = min(src_args.Load(src_at), 1u << 24);
        uint instances = min(src_args.Load(src_at + 4), (1u << 26) / max(count, 1u));
        cost = count * instances;
        draw_counts = uint2(count, instances);
    } else if (kind == 2) {
        uint3 g = min(src_args.Load3(src_at), uint3(65535u, 65535u, 65535u));
        // x * y fits 32 bits; the whole count may not.
        if (g.z != 0 && g.x * g.y > GROUPS / g.z) {
            g = uint3(0, 0, 0);
        }
        cost = g.x * g.y * g.z * 64u;
        groups = g;
    } else {
        uint3 g = src_args.Load3(src_at);
#ifdef MESH_2D
        g = min(g, uint3(65535u, 65535u, 65535u));
        // All nonzero inside: MESH_GROUPS / g.z is 64 or more.
        if (g.y != 0 && g.z != 0 && g.x * g.y > MESH_GROUPS / g.z) {
            g.z = min(g.z, max(1u, MESH_GROUPS / (g.x * g.y)));
            g.y = min(g.y, max(1u, MESH_GROUPS / (g.x * g.z)));
            g.x = min(g.x, MESH_GROUPS / (g.y * g.z));
        }
#else
        // Mesh dispatches: the console's are one-dimensional.
        g = uint3(min(g.x, 65535u), min(g.y, 1u), min(g.z, 1u));
#endif
        cost = g.x * g.y * g.z * 128u;
        groups = g;
    }
    bool over = false;
    if (cost > 0) {
        uint before;
        budget.InterlockedOr(0, 0, before);
        // Bounded retries: an unbounded loop of atomics is a GPU hang if
        // contention never settles; a record that gives up runs empty.
        bool settled = false;
        [allow_uav_condition]
        for (uint tries = 0; tries < 256 && before < BUDGET; tries++) {
            uint next = (BUDGET - before <= cost) ? BUDGET : (before + cost);
            uint prev;
            budget.InterlockedCompareExchange(0, before, next, prev);
            if (prev == before) { settled = true; break; }
            before = prev;
        }
        over = !settled || before >= BUDGET || BUDGET - before < cost;
    }
#ifdef STATS
    {
        uint bucket = kind <= 1 ? 0u : (kind == 2 ? 1u : 2u);
        uint at = STATS_AT + bucket * 32u;
        bool zero;
        bool clamped;
        uint launched;
        if (kind <= 1) {
            zero = seen.x == 0 && seen.y == 0;
            clamped = any(draw_counts != seen.xy);
            launched = over ? 0u : draw_counts.x * draw_counts.y;
        } else {
            zero = all(seen == uint3(0, 0, 0));
            clamped = any(groups != seen);
            launched = over ? 0u : groups.x * groups.y * groups.z;
        }
        uint ignored;
        budget.InterlockedAdd(at, 1u, ignored);
        if (zero) budget.InterlockedAdd(at + 4u, 1u, ignored);
        if (over) budget.InterlockedAdd(at + 8u, 1u, ignored);
        if (clamped) budget.InterlockedAdd(at + 12u, 1u, ignored);
        if (bucket == 2u) {
            budget.InterlockedMax(at + 16u, seen.y, ignored);
            budget.InterlockedMax(at + 20u, seen.z, ignored);
        }
        // 64 bits: a carry out of the low word goes to the high one.
        uint low;
        budget.InterlockedAdd(at + 24u, launched, low);
        if (low + launched < low) budget.InterlockedAdd(at + 28u, 1u, ignored);
    }
#endif
    if (kind <= 1) {
        if (over) {
            draw_counts = uint2(0, 0);
        }
        dst_args.Store2(dst_at, draw_counts);
        for (uint off = 8; off < stride; off += 4) {
            dst_args.Store(dst_at + off, src_args.Load(src_at + off));
        }
    } else {
        if (over) {
            groups = uint3(0, 0, 0);
        }
        dst_args.Store3(dst_at, groups);
        for (uint off = 12; off < stride; off += 4) {
            dst_args.Store(dst_at + off, src_args.Load(src_at + off));
        }
    }
}
"#;

/// The experiment switches (see the module's notes), read once.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
struct Config {
    /// `VICTORY_MESH_2D=1`: mesh dispatches keep y and z.
    mesh_2d: bool,
    /// `VICTORY_INDIRECT_BUDGET_SHIFT`: the budget is `1 << budget_shift`.
    budget_shift: u32,
    /// `VICTORY_INDIRECT_STATS=1` (diagnostics only): the clamp counts.
    stats: bool,
}

/// The default budget's shift: 2^27 vertex instances or threads per list.
const BUDGET_SHIFT: u32 = 27;

/// Byte offset of the counters in the budget buffer (the shader's
/// `STATS_AT`), 8 words for each of draws, dispatches and mesh.
#[cfg(feature = "diagnostics")]
const STATS_AT: usize = 64;

impl Config {
    const DEFAULT: Config = Config {
        mesh_2d: false,
        budget_shift: BUDGET_SHIFT,
        stats: false,
    };
}

fn config() -> Config {
    static CONFIG: std::sync::OnceLock<Config> = std::sync::OnceLock::new();
    *CONFIG.get_or_init(|| {
        let on = |name: &str| std::env::var(name).is_ok_and(|v| v == "1");
        let c = Config {
            mesh_2d: on("VICTORY_MESH_2D"),
            budget_shift: budget_shift(
                std::env::var("VICTORY_INDIRECT_BUDGET_SHIFT")
                    .ok()
                    .as_deref(),
            ),
            stats: cfg!(feature = "diagnostics") && on("VICTORY_INDIRECT_STATS"),
        };
        if c != Config::DEFAULT {
            tracing::info!(
                mesh_2d = c.mesh_2d,
                budget = format_args!("2^{}", c.budget_shift),
                stats = c.stats,
                "indirect argument clamp: experiment switches on"
            );
        }
        c
    })
}

/// The budget's shift from `VICTORY_INDIRECT_BUDGET_SHIFT`: at most 31 (a
/// 32-bit word), the default when unset or not a number.
fn budget_shift(value: Option<&str>) -> u32 {
    value
        .and_then(|v| v.trim().parse::<u32>().ok())
        .map_or(BUDGET_SHIFT, |n| n.min(31))
}

/// Whether the clamp counts (`VICTORY_INDIRECT_STATS=1`, diagnostics).
pub(crate) fn stats_on() -> bool {
    config().stats
}

struct Clamp {
    root: ID3D12RootSignature,
    pso: ID3D12PipelineState,
}

// SAFETY: D3D12 objects are free-threaded.
unsafe impl Send for Clamp {}
// SAFETY: as above.
unsafe impl Sync for Clamp {}

fn clamp() -> Option<&'static Clamp> {
    static CLAMP: std::sync::OnceLock<Option<Clamp>> = std::sync::OnceLock::new();
    CLAMP
        .get_or_init(|| match make() {
            Ok(c) => Some(c),
            Err(e) => {
                tracing::warn!(error = %e, "no argument clamp: indirect execution dropped");
                None
            }
        })
        .as_ref()
}

fn make() -> windows::core::Result<Clamp> {
    let device = &host().ok_or_else(windows::core::Error::empty)?.device;
    make_with(device, config())
}

#[cfg(test)]
fn make_for(device: &ID3D12Device) -> windows::core::Result<Clamp> {
    make_with(device, Config::DEFAULT)
}

fn make_with(device: &ID3D12Device, config: Config) -> windows::core::Result<Clamp> {
    // Defines only for switches that are on: by default the shader compiles
    // from exactly the source it always did.
    let shift = format!("{}\0", config.budget_shift);
    let mut defines = Vec::new();
    if config.budget_shift != BUDGET_SHIFT {
        defines.push(D3D_SHADER_MACRO {
            Name: s!("BUDGET_SHIFT"),
            Definition: PCSTR(shift.as_ptr()),
        });
    }
    if config.mesh_2d {
        defines.push(D3D_SHADER_MACRO {
            Name: s!("MESH_2D"),
            Definition: s!("1"),
        });
    }
    if config.stats {
        defines.push(D3D_SHADER_MACRO {
            Name: s!("STATS"),
            Definition: s!("1"),
        });
    }
    let defines = (!defines.is_empty()).then(|| {
        defines.push(D3D_SHADER_MACRO::default());
        defines
    });
    let mut code: Option<ID3DBlob> = None;
    let mut errors: Option<ID3DBlob> = None;
    // SAFETY: the source and names live through the call; out pointers ours.
    let compiled = unsafe {
        D3DCompile(
            SOURCE.as_ptr().cast(),
            SOURCE.len(),
            s!("clamp"),
            defines.as_ref().map(|d| d.as_ptr()),
            None,
            s!("main"),
            s!("cs_5_1"),
            0,
            0,
            &mut code,
            Some(&mut errors),
        )
    };
    if let Err(e) = compiled {
        if let Some(errors) = errors {
            // SAFETY: the blob's own bytes.
            let text = unsafe {
                std::slice::from_raw_parts(
                    errors.GetBufferPointer().cast::<u8>(),
                    errors.GetBufferSize(),
                )
            };
            tracing::warn!("argument clamp: {}", String::from_utf8_lossy(text));
        }
        return Err(e);
    }
    let code = code.ok_or_else(windows::core::Error::empty)?;
    // SAFETY: the blob's own bytes; the root signature is inside the shader.
    unsafe {
        let bytes =
            std::slice::from_raw_parts(code.GetBufferPointer().cast::<u8>(), code.GetBufferSize());
        let root: ID3D12RootSignature = device.CreateRootSignature(0, bytes)?;
        let pso = device.CreateComputePipelineState(&D3D12_COMPUTE_PIPELINE_STATE_DESC {
            pRootSignature: std::mem::transmute_copy(&root),
            CS: D3D12_SHADER_BYTECODE {
                pShaderBytecode: bytes.as_ptr().cast(),
                BytecodeLength: bytes.len(),
            },
            ..Default::default()
        })?;
        Ok(Clamp { root, pso })
    }
}

/// Minimum record byte stride for a supported PC indirect argument `kind`.
fn min_stride(kind: u32) -> Option<u32> {
    match kind {
        0 => Some(16),
        1 => Some(20),
        2 | 10 => Some(12),
        _ => None,
    }
}

/// Validates record alignment and returns the scratch byte size `stride * records`.
fn validate_layout(
    (kind, stride, records): (u32, u32, u32),
    src_offset: u64,
    count_offset: Option<u64>,
) -> Option<u64> {
    let min = min_stride(kind)?;
    if stride < min || !stride.is_multiple_of(4) || !src_offset.is_multiple_of(4) {
        return None;
    }
    if count_offset.is_some_and(|off| !off.is_multiple_of(4)) {
        return None;
    }
    let bytes = u64::from(stride).checked_mul(u64::from(records))?;
    (bytes <= u64::from(u32::MAX)).then_some(bytes)
}

/// Records, in `list`, the non-destructive clamp of up to `records` records of
/// `kind` (PC argument numbering) `stride` bytes apart from `src` (and bounded
/// by the 32-bit count in `count` when given) into a device-local scratch
/// buffer, leaving that scratch buffer in `INDIRECT_ARGUMENT` at offset `0`.
/// Replaces the list's compute root signature and pipeline (callers bind
/// theirs after). `None` if the clamp or alignment is not available.
pub(crate) fn bound(
    list: &HostList,
    src: (&ID3D12Resource, u64),
    count: Option<(&ID3D12Resource, u64)>,
    spec: (u32, u32, u32),
) -> Option<ID3D12Resource> {
    bound_why(list, src, count, spec).ok()
}

/// As [`bound`], saying why the arguments could not be bounded.
pub(crate) fn bound_why(
    list: &HostList,
    src: (&ID3D12Resource, u64),
    count: Option<(&ID3D12Resource, u64)>,
    spec: (u32, u32, u32),
) -> Result<ID3D12Resource, String> {
    let (kind, stride, records) = spec;
    let bytes = validate_layout(spec, src.1, count.map(|(_, off)| off)).ok_or_else(|| {
        format!(
            "layout (stride {stride}, records {records}, offset mod 4 {}, count offset mod 4 {:?})",
            src.1 % 4,
            count.map(|(_, off)| off % 4)
        )
    })?;
    let c = clamp().ok_or("no clamp pipeline")?;
    let budget = list.budget().ok_or("no budget buffer")?;
    let dst = list
        .indirect_scratch(bytes)
        .ok_or_else(|| format!("no scratch buffer of {bytes} bytes"))?;
    if !record_clamp(c, &list.list, &dst, budget, src, count, spec) {
        // SAFETY: a live buffer.
        let base = unsafe { src.0.GetGPUVirtualAddress() };
        return Err(format!(
            "clamp not recorded (kind {kind}, source base mod 4 {}, offset mod 4 {}, past 4 GiB {})",
            base % 4,
            src.1 % 4,
            src.1 > u64::from(u32::MAX)
        ));
    }
    Ok(dst)
}

fn record_clamp(
    c: &Clamp,
    l: &ID3D12GraphicsCommandList,
    dst: &ID3D12Resource,
    budget: u64,
    (src, src_offset): (&ID3D12Resource, u64),
    count: Option<(&ID3D12Resource, u64)>,
    (kind, stride, records): (u32, u32, u32),
) -> bool {
    let Some(bytes) = validate_layout(
        (kind, stride, records),
        src_offset,
        count.map(|(_, off)| off),
    ) else {
        return false;
    };
    // SAFETY: live D3D12 buffer resources.
    let (src_base, dst_gpu) = unsafe { (src.GetGPUVirtualAddress(), dst.GetGPUVirtualAddress()) };
    if !src_base.is_multiple_of(4) || !dst_gpu.is_multiple_of(4) || !budget.is_multiple_of(4) {
        return false;
    }
    let (src_gpu, args_offset) = match src_offset
        .checked_add(bytes)
        .filter(|&end| end <= u64::from(u32::MAX))
    {
        Some(_) => (src_base, src_offset as u32),
        None => {
            let Some(rebased) = src_base.checked_add(src_offset) else {
                return false;
            };
            (rebased, 0)
        }
    };
    let (count_gpu, has_count, count_offset) = match count {
        Some((buf, off)) => {
            // SAFETY: a live D3D12 buffer resource.
            let base = unsafe { buf.GetGPUVirtualAddress() };
            if !base.is_multiple_of(4) {
                return false;
            }
            match off.checked_add(4).filter(|&end| end <= u64::from(u32::MAX)) {
                Some(_) => (base, 1u32, off as u32),
                None => {
                    let Some(rebased) = base.checked_add(off) else {
                        return false;
                    };
                    (rebased, 1u32, 0u32)
                }
            }
        }
        None => (src_gpu, 0u32, 0u32),
    };
    let constants = [kind, stride, records, args_offset, has_count, count_offset];
    // SAFETY: an open list; our root signature and pipeline; live source,
    // count, scratch destination, and budget buffers. `src` and `count` stay
    // in `COMMON` / `GENERIC_READ` via implicit buffer promotion while `dst`
    // transitions `COMMON -> UNORDERED_ACCESS -> INDIRECT_ARGUMENT`.
    unsafe {
        // Earlier shader writes (the title's argument and count passes) first.
        l.ResourceBarrier(&[
            uav_barrier(),
            transition(
                dst,
                D3D12_RESOURCE_STATE_COMMON,
                D3D12_RESOURCE_STATE_UNORDERED_ACCESS,
            ),
        ]);
        if records > 0 {
            l.SetComputeRootSignature(&c.root);
            l.SetPipelineState(&c.pso);
            l.SetComputeRoot32BitConstants(0, 6, constants.as_ptr().cast(), 0);
            l.SetComputeRootShaderResourceView(1, src_gpu);
            l.SetComputeRootShaderResourceView(2, count_gpu);
            l.SetComputeRootUnorderedAccessView(3, dst_gpu);
            l.SetComputeRootUnorderedAccessView(4, budget);
            l.Dispatch(records.div_ceil(64), 1, 1);
        }
        l.ResourceBarrier(&[
            uav_barrier(),
            transition(
                dst,
                D3D12_RESOURCE_STATE_UNORDERED_ACCESS,
                D3D12_RESOURCE_STATE_INDIRECT_ARGUMENT,
            ),
        ]);
    }
    true
}

/// The clamp's counters (`VICTORY_INDIRECT_STATS`) of finished lists
/// since the last line: per kind bucket (draws, dispatches, mesh) records,
/// all-zero records, records over the budget, records clamped, launched
/// (vertex instances or groups); then the lists that counted and those
/// that used up their budget.
#[cfg(feature = "diagnostics")]
static STATS: [std::sync::atomic::AtomicU64; 17] =
    [const { std::sync::atomic::AtomicU64::new(0) }; 17];
/// The largest mesh y and z the title wrote since the last line.
#[cfg(feature = "diagnostics")]
static MESH_MAX: [std::sync::atomic::AtomicU32; 2] =
    [const { std::sync::atomic::AtomicU32::new(0) }; 2];

/// Words of the budget buffer [`collect`] reads: the budget and counters.
#[cfg(feature = "diagnostics")]
pub(crate) const STATS_WORDS: usize = STATS_AT / 4 + 3 * 8;

/// Adds a finished list's counters: `words` is the start of its budget
/// buffer, as the submission left it.
#[cfg(feature = "diagnostics")]
pub(crate) fn collect(words: &[u32; STATS_WORDS]) {
    use std::sync::atomic::Ordering::Relaxed;
    for bucket in 0..3 {
        let w = &words[STATS_AT / 4 + bucket * 8..][..8];
        for (i, &n) in w[..4].iter().enumerate() {
            STATS[bucket * 5 + i].fetch_add(u64::from(n), Relaxed);
        }
        STATS[bucket * 5 + 4].fetch_add(u64::from(w[6]) | u64::from(w[7]) << 32, Relaxed);
        if bucket == 2 {
            MESH_MAX[0].fetch_max(w[4], Relaxed);
            MESH_MAX[1].fetch_max(w[5], Relaxed);
        }
    }
    STATS[15].fetch_add(1, Relaxed);
    let budget = 1u64 << config().budget_shift;
    if u64::from(words[0]) >= budget {
        STATS[16].fetch_add(1, Relaxed);
    }
}

/// Logs the counters per frame over `frames` and starts them again, with
/// `VICTORY_INDIRECT_STATS=1` only.
#[cfg(feature = "diagnostics")]
pub(crate) fn log_stats(frames: f64) {
    use std::sync::atomic::Ordering::Relaxed;
    if !stats_on() {
        return;
    }
    let c: Vec<f64> = STATS
        .iter()
        .map(|a| a.swap(0, Relaxed) as f64 / frames)
        .collect();
    let [y, z] = [0, 1].map(|i| MESH_MAX[i].swap(0, Relaxed));
    let c = &c;
    let bucket = |b: usize| {
        format!(
            "{:.0} run, {:.0} all zero, {:.0} over budget, {:.0} clamped, {:.2}M launched",
            c[b * 5],
            c[b * 5 + 1],
            c[b * 5 + 2],
            c[b * 5 + 3],
            c[b * 5 + 4] / 1e6
        )
    };
    let switches = config();
    tracing::info!(
        "indirect per frame: draws {}; dispatches {}; mesh {} (max y {y}, z {z}); \
         {:.1} lists, {:.1} of them out of budget (2^{}, mesh {})",
        bucket(0),
        bucket(1),
        bucket(2),
        c[15],
        c[16],
        switches.budget_shift,
        if switches.mesh_2d { "2D" } else { "1D" },
    );
}

/// After indirect execution (or if preparation failed after [`bound`]):
/// returns the scratch buffer to the common state for the next call.
pub(crate) fn done(list: &HostList, scratch: &ID3D12Resource) {
    done_on(&list.list, scratch);
}

fn done_on(list: &ID3D12GraphicsCommandList, scratch: &ID3D12Resource) {
    // SAFETY: an open list and a live scratch buffer in INDIRECT_ARGUMENT.
    unsafe {
        list.ResourceBarrier(&[transition(
            scratch,
            D3D12_RESOURCE_STATE_INDIRECT_ARGUMENT,
            D3D12_RESOURCE_STATE_COMMON,
        )])
    };
}

fn uav_barrier() -> D3D12_RESOURCE_BARRIER {
    D3D12_RESOURCE_BARRIER {
        Type: D3D12_RESOURCE_BARRIER_TYPE_UAV,
        Flags: D3D12_RESOURCE_BARRIER_FLAG_NONE,
        Anonymous: D3D12_RESOURCE_BARRIER_0 {
            UAV: std::mem::ManuallyDrop::new(D3D12_RESOURCE_UAV_BARRIER {
                pResource: std::mem::ManuallyDrop::new(None),
            }),
        },
    }
}

